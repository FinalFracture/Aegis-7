def _mirror(m):
    """Flip X and rewind. metadata['uv'] stays with the same vertex order."""
    uv = m.metadata.get('uv') if getattr(m, 'metadata', None) else None
    m.vertices[:, 0] *= -1
    m.invert()
    if uv is not None:
        m.metadata['uv'] = uv
    return m


