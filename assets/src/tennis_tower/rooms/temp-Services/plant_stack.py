def check_aperture(parts):
    viol, xs, zs = [], [], []
    y_min, y_max = float('inf'), float('-inf')
    for name, _, ms in parts:
        for m in ms:
            if m is None or len(getattr(m, 'vertices', [])) == 0:
                continue
            V = np.asarray(m.vertices, float)
            y_min = min(y_min, float(V[:, 1].min()))
            y_max = max(y_max, float(V[:, 1].max()))
            hi = V[V[:, 1] > ROOF_CUT_Y]
            if len(hi) == 0:
                continue
            ax, az = np.abs(hi[:, 0]), np.abs(hi[:, 2])
            xs.append(float(ax.max()))
            zs.append(float(az.max()))
            bad = (ax > APX + 1e-6) | (az > APZ + 1e-6)
            if np.any(bad):
                viol.append('%s: %d verts |x|=%.4f |z|=%.4f' % (
                    name, int(bad.sum()), float(ax.max()), float(az.max())))
    if y_min < -1e-6:
        viol.append('y_min %.6f' % y_min)
    if y_max > YMAX + 1e-6:
        viol.append('y_max %.6f' % y_max)
    y_ok = y_min >= -1e-6 and y_max <= YMAX + 1e-6
    return {
        'pass': (len(viol) == 0) and y_ok,
        'violations': viol,
        'max_abs_x': max(xs) if xs else 0.0,
        'max_abs_z': max(zs) if zs else 0.0,
        'y_min': None if y_min == float('inf') else y_min,
        'y_max': None if y_max == float('-inf') else y_max,
    }


def placements(r_by_asset):
    out = []
    for corner, (cx, cz, yaw, asset) in CORNERS.items():
        off = r_by_asset[asset]['world_offset']
        if yaw == 180:
            p = (cx - off[0], off[1], cz - off[2])
        else:
            p = (cx + off[0], off[1], cz + off[2])
        out.append(dict(
            corner=corner, asset=asset, glb='res://assets/models/%s.glb' % asset,
            p=[round(float(v), 4) for v in p], yaw=yaw))
    return out


def _rot(T, deg, axis):
    T = np.asarray(T, float)
    R = trimesh.transformations.rotation_matrix(np.radians(deg), axis)
    if T.shape == (4, 4):
        return R @ T
    if T.shape == (3, 3):
        return R[:3, :3] @ T
    return T


def _render(geo, prefix):
    vis = {k: v for k, v in geo.items() if 'colonly' not in k}
    vs = views()
    iso, front, side = vs[3], vs[1], vs[2]
    aerial = _rot(_rot(np.eye(3), 35, [0, 1, 0]), 55, [1, 0, 0])  # Rx(55) @ Ry(35)
    rear = _rot(iso, 180, [0, 1, 0])
    for tag, T in (('iso', iso), ('front', front), ('side', side), ('aerial', aerial), ('rear', rear)):
        im = render_view(vis, T, size=900, shadow=True)
        plt.imsave(str(RD / ('%s_%s.png' % (prefix, tag))), np.clip(crop(im), 0, 1))


def main():
    REP = []
    r_by, geo_by, ap_by = {}, {}, {}
    order = (('base', 'tt_services_plant_stack'),
             ('sw', 'tt_services_plant_stack_sw'),
             ('m', 'tt_services_plant_stack_m'),
             ('m_nw', 'tt_services_plant_stack_m_nw'))
    for variant, name in order:
        parts, cols = build(variant)
        ap = check_aperture(parts)
        r, geo = export_chunk(name, parts, cols, report=REP, note=NOTE)
        r_by[name], geo_by[name], ap_by[name] = r, geo, ap
        print(json.dumps(dict(
            asset=name, tris=r.get('tris'), passed=r.get('passed'),
            aperture_pass=ap['pass'], max_abs_x=ap['max_abs_x'], max_abs_z=ap['max_abs_z'])))
    os.makedirs(RD, exist_ok=True)
    payload = dict(
        assets={n: dict(r=r_by[n], aperture=ap_by[n]) for _, n in order},
        placements=placements(r_by),
        constants=dict(
            footprint=dict(x0=WX0, x1=WX1, z0=WZ0, z1=WZ1),
            cap_footprint=dict(x0=CX0, x1=CX1, z0=CZ0, z1=CZ1),
            aperture=dict(APX=APX, APZ=APZ, ROOF_CUT_Y=ROOF_CUT_Y, YMAX=YMAX)))
    json.dump(payload, open(RD / 'plant_stack_report.json', 'w'), indent=1, default=str)
    _render(geo_by['tt_services_plant_stack'], 'plant_stack')
    _render(geo_by['tt_services_plant_stack_m'], 'plant_stack_m')


if __name__ == '__main__':
    main()
