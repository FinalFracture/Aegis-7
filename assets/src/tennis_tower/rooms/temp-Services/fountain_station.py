def _aabb(m):
    return np.asarray(m.bounds, float)


def _xz_hit(lo, hi, x0, x1, z0, z1):
    return not (hi[0] <= x0 or lo[0] >= x1 or hi[2] <= z0 or lo[2] >= z1)


def check_envelopes(parts):
    viol = []
    a0, a1 = APPROACH
    for a in APPROACH:
        if a['z1'] > 1.30 + 1e-6:
            viol.append(f"{a['name']} z1={a['z1']} outside recess")
        if a['x0'] < -1.20 - 1e-6 or a['x1'] > 1.20 + 1e-6:
            viol.append(f"{a['name']} x outside recess")
    if not (a0['x1'] <= a1['x0'] or a1['x1'] <= a0['x0'] or a0['z1'] <= a1['z0'] or a1['z1'] <= a0['z0']):
        viol.append('approach rects overlap')
    knee_y, toe_y = 99.0, 99.0
    low = a0
    for n, mk, ms in parts:
        for m in ms:
            if m is None or len(getattr(m, 'vertices', [])) == 0:
                continue
            lo, hi = _aabb(m)
            if hi[2] > 1.34 + 1e-6 and hi[1] > .006:
                viol.append(f'{n} protrudes z={hi[2]:.4f}')
            tall = bool(np.any(m.vertices[:, 1] > .006))
            if tall:
                for a in APPROACH:
                    if not _xz_hit(lo, hi, a['x0'], a['x1'], a['z0'], a['z1']):
                        continue
                    ok = ((hi[2] <= KNEE['z_max'] + 1e-4 and lo[1] >= KNEE['y_min'] - 1e-4)
                          or lo[1] >= 2.38)
                    if not ok:
                        viol.append(f"{n} blocks {a['name']} approach y={lo[1]:.3f} z={hi[2]:.3f}")
            if tall and _xz_hit(lo, hi, low['x0'], low['x1'], 0.0, KNEE['z_max']):
                knee_y = min(knee_y, float(lo[1]))
            if tall and _xz_hit(lo, hi, low['x0'], low['x1'], 0.0, 0.64):
                toe_y = min(toe_y, float(lo[1]))
    if knee_y < KNEE['y_min'] - 1e-4:
        viol.append(f'knee clearance {knee_y:.3f} < {KNEE["y_min"]}')
    return {
        'pass': len(viol) == 0,
        'violations': viol,
        'knee_clearance': None if knee_y > 90 else round(knee_y, 3),
        'toe_clearance': None if toe_y > 90 else round(toe_y, 3),
    }


def _rot(T, deg, axis):
    T = np.asarray(T, float)
    R = trimesh.transformations.rotation_matrix(np.radians(deg), axis)
    if T.shape == (4, 4):
        return R @ T
    if T.shape == (3, 3):
        return R[:3, :3] @ T
    return T


def main():
    parts, cols = build()
    env = check_envelopes(parts)
    r, geo = export_chunk('tt_services_fountain_station', parts, cols, report=REP,
                          note='temp-Services combined drinking station')
    vis = {k: v for k, v in geo.items() if 'colonly' not in k}
    summary = dict(
        tris=r.get('tris'), passed=r.get('passed'), env=env,
        counts=dict(stations_per_module=1,
                    outlets_per_module=dict(accessible_low=1, standing=1, bottle_filler=1)))
    print(json.dumps(summary, default=str))
    os.makedirs(RD, exist_ok=True)
    json.dump({**summary, 'r': r}, open(RD / 'fountain_station_report.json', 'w'), indent=1, default=str)
    vs = views()
    iso, front, side = vs[3], vs[1], vs[2]
    iso2 = _rot(_rot(np.eye(3), -35, [0, 1, 0]), 28, [1, 0, 0])  # Rx(28) @ Ry(-35): front-right 3/4
    low = _rot(_rot(front, 8, [1, 0, 0]), -40, [0, 1, 0])
    for tag, T in (('iso', iso), ('front', front), ('side', side), ('iso2', iso2), ('low', low)):
        im = render_view(vis, T, size=900, shadow=True)
        plt.imsave(str(RD / f'fountain_station_{tag}.png'), np.clip(crop(im), 0, 1))
    # top plan in recentred coords
    ox, oy, oz = r['world_offset']
    fig, ax = plt.subplots(figsize=(8.2, 5.6), facecolor='white')
    for k, v in vis.items():
        V = np.asarray(v[1], float)
        lo, hi = V.min(0), V.max(0)
        ax.add_patch(plt.Rectangle((lo[0], lo[2]), hi[0] - lo[0], hi[2] - lo[2],
                                   facecolor='#d8d8d8', edgecolor='#b0b0b0', lw=.4, alpha=.7))
    for a in APPROACH:
        ax.add_patch(plt.Rectangle((a['x0'] - ox, a['z0'] - oz), a['x1'] - a['x0'], a['z1'] - a['z0'],
                                   fill=False, edgecolor='#2ca02c', lw=1.6))
        ax.text(.5 * (a['x0'] + a['x1']) - ox, .5 * (a['z0'] + a['z1']) - oz, a['name'],
                color='#2ca02c', ha='center', va='center', fontsize=9)
    kn = APPROACH[0]
    ax.add_patch(plt.Rectangle((kn['x0'] - ox, 0.0 - oz), kn['x1'] - kn['x0'], KNEE['z_max'],
                               fill=False, edgecolor='#6a3d9a', lw=1.2, linestyle='--'))
    ax.text(.5 * (kn['x0'] + kn['x1']) - ox, KNEE['z_max'] * .5 - oz, 'knee',
            color='#6a3d9a', ha='center', va='center', fontsize=8)
    ax.set_aspect('equal', adjustable='box'); ax.set_xlabel('X (m)'); ax.set_ylabel('Z (m)')
    ax.set_xlim(-1.5, 1.5); ax.set_ylim(-0.8, 0.8)
    ax.set_title('tt_services_fountain_station plan (recentred)')
    fig.savefig(RD / 'fountain_station_plan.png', dpi=120, bbox_inches='tight')
    plt.close(fig)


if __name__ == '__main__':
    main()
