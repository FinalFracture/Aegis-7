def _add(g, n, mk, *ms):
    g.setdefault((n, mk), []).extend(m for m in ms if m is not None)


def _bowl(g, name, cx, y_rim, y_bot, z1, spout_y, btn_y):
    """Wall-hung dish: 4 rim walls + 4-plate floor with square drain + slats + spout."""
    hw, wt, ft, hr = .16, .026, .016, .018
    x0, x1, z0 = cx - hw, cx + hw, -E
    yf = y_bot + ft
    xi0, xi1, zi0, zi1 = x0 + wt, x1 - wt, z0 + wt, z1 - wt
    hx0, hx1 = cx - hr, cx + hr
    hzc = .5 * (zi0 + zi1); hz0, hz1 = hzc - hr, hzc + hr
    # rim (gunmetal)
    _add(g, name, G,
         box(x0, x1, yf - E, y_rim, z0, zi0 + E),
         box(x0, x1, yf - E, y_rim, zi1 - E, z1),
         box(x0, xi0 + E, yf - E, y_rim, zi0, zi1),
         box(xi1 - E, x1, yf - E, y_rim, zi0, zi1))
    # floor plate around drain hole
    _add(g, name, G,
         box(xi0, xi1, y_bot, yf, zi0, hz0),
         box(xi0, xi1, y_bot, yf, hz1, zi1),
         box(xi0, hx0, y_bot, yf, hz0 - E, hz1 + E),
         box(hx1, xi1, y_bot, yf, hz0 - E, hz1 + E))
    # wall bracket (above y_bot only) + side ears
    _add(g, name, G,
         box(cx - .10, cx + .10, y_bot, y_rim + .04, -E, .016),
         box(x0, x0 + .02, y_bot, y_bot + .08, -E, .10),
         box(x1 - .02, x1, y_bot, y_bot + .08, -E, .10))
    sn = name + '_Steel'
    # steel rim cap: embed E into the rim, top E proud (distinct from the bowl face); end faces inset 2 mm
    _add(g, sn, ST,
         box(x0 + .004, x1 - .004, y_rim - E, y_rim + E, z0 + .004, zi0 + .008),
         box(x0 + .004, x1 - .004, y_rim - E, y_rim + E, zi1 - .008, z1 - .004),
         box(x0 + .004, xi0 + .008, y_rim - E, y_rim + E, zi0 + .002, zi1 - .002),
         box(xi1 - .008, x1 - .004, y_rim - E, y_rim + E, zi0 + .002, zi1 - .002))
    # drain grille: 3 slats spanning the hole, embed 4 mm into plate edges
    step = (hx1 - hx0) / 4.0
    _add(g, sn, ST, *[
        box(hx0 + step * (i + 1) - .003, hx0 + step * (i + 1) + .003,
            yf - E, yf + .002, hz0 - E, hz1 + E) for i in range(3)])
    # spout: short tube rising from the bowl back
    sx, sz = cx, zi0 + .028
    _add(g, sn, ST,
         tube((sx, yf - E, sz), (sx, spout_y, sz), .011, 6),
         tube((sx, spout_y, sz - E), (sx, spout_y, sz + .09), .009, 6),
         cap((sx, spout_y, sz + .09), .008, .006, 6, 'z'))
    # tennis-ball-yellow front push-button (node, 4 mm embed, z_max <= 0.48)
    br = .012
    _add(g, name + '_Button', BA, node((cx, btn_y, z1 + br - E), br, 0))
    return box(x0, x1, y_bot, y_rim, 0.0, z1)


